type Compiler struct {
	CampaignDir string
	PDFEngine   string
}

func New(campaignDir, pdfEngine string) *Compiler {
	if pdfEngine == "" {
		pdfEngine = "wkhtmltopdf"
	}
	return &Compiler{
		CampaignDir: campaignDir,
		PDFEngine:   pdfEngine,
	}
}

func GetTemplate(tmplType string) (string, error) {
	switch tmplType {
	case "act":
		return actTemplate, nil
	case "npc":
		return npcTemplate, nil
	case "monster":
		return monsterTemplate, nil
	case "encounter":
		return encounterTemplate, nil
	case "map":
		return mapTemplate, nil
	case "lore":
		return loreTemplate, nil
	default:
		return "", fmt.Errorf("unknown template type: %s", tmplType)
	}
}

type tocEntry struct {
	name string
	id   string
}

func (c *Compiler) Compile(title string) (string, error) {
	sections := []struct {
		name string
		path string
	}{
		{"README", filepath.Join(c.CampaignDir, "README.md")},
		{"Lore", filepath.Join(c.CampaignDir, "lore.md")},
		{"Acts", filepath.Join(c.CampaignDir, "acts")},
		{"NPCs", filepath.Join(c.CampaignDir, "npcs")},
		{"Bestiary", filepath.Join(c.CampaignDir, "bestiary")},
		{"Encounters", filepath.Join(c.CampaignDir, "encounters")},
		{"Maps", filepath.Join(c.CampaignDir, "maps")},
	}

	var htmlParts []string
	headingCounter := 0

	htmlParts = append(htmlParts, "<!DOCTYPE html>")
	htmlParts = append(htmlParts, "<html><head><meta charset='utf-8'>")
	htmlParts = append(htmlParts, "<style>"+dndCSS+"</style>")
	htmlParts = append(htmlParts, "</head><body>")

	// Cover page — single page, no split
	htmlParts = append(htmlParts, fmt.Sprintf(`<div class="cover" id="cover"><h1>%s</h1><p class="subtitle">Generated by Grimorio</p></div>`, html.EscapeString(title)))

	// TOC
	htmlParts = append(htmlParts, `<div class="toc" id="toc"><h2>Table of Contents</h2><ul>`)
	for _, sec := range sections {
		if _, err := os.Stat(sec.path); err == nil {
			id := "sec-" + sanitizeID(sec.name)
			htmlParts = append(htmlParts, fmt.Sprintf(`<li><a href="#%s">%s</a><span class="page-ref"></span></li>`, id, html.EscapeString(sec.name)))
		}
	}
	htmlParts = append(htmlParts, `</ul></div>`)
	htmlParts = append(htmlParts, `<div class="section-break"></div>`)

	for _, sec := range sections {
		info, err := os.Stat(sec.path)
		if err != nil {
			continue
		}

		if info.IsDir() {
			files, err := os.ReadDir(sec.path)
			if err != nil {
				continue
			}
			hasContent := false
			for _, f := range files {
				if strings.HasSuffix(f.Name(), ".md") {
					content, err := os.ReadFile(filepath.Join(sec.path, f.Name()))
					if err != nil {
						continue
					}
					sectionID := "sec-" + sanitizeID(sec.name+"-"+f.Name())
					htmlResult := markdownToHTMLWithID(string(content), c.CampaignDir, sectionID, &headingCounter)
					if strings.TrimSpace(htmlResult) != "" {
						htmlParts = append(htmlParts, htmlResult)
						hasContent = true
					}
				}
			}
			if hasContent {
				htmlParts = append(htmlParts, `<div class="section-break"></div>`)
			}
		} else {
			content, err := os.ReadFile(sec.path)
			if err != nil {
				continue
			}
			sectionID := "sec-" + sanitizeID(sec.name)
			htmlResult := markdownToHTMLWithID(string(content), c.CampaignDir, sectionID, &headingCounter)
			if strings.TrimSpace(htmlResult) != "" {
				htmlParts = append(htmlParts, htmlResult)
			}
			htmlParts = append(htmlParts, `<div class="section-break"></div>`)
		}
	}

	htmlParts = append(htmlParts, "</body></html>")

	htmlPath := filepath.Join(c.CampaignDir, "campaign.html")
	if err := os.WriteFile(htmlPath, []byte(strings.Join(htmlParts, "\n")), 0644); err != nil {
		return "", fmt.Errorf("failed to write HTML: %w", err)
	}

	pdfPath := filepath.Join(c.CampaignDir, "campaign.pdf")
	if err := c.htmlToPDF(htmlPath, pdfPath); err != nil {
		return "", fmt.Errorf("failed to convert to PDF: %w", err)
	}

	return pdfPath, nil
}

func sanitizeID(s string) string {
	result := []rune(s)
	for i, r := range result {
		if (r < 'a' || r > 'z') && (r < 'A' || r > 'Z') && (r < '0' || r > '9') {
			result[i] = '-'
		}
	}
	return strings.ToLower(string(result))
}

func (c *Compiler) htmlToPDF(htmlPath, pdfPath string) error {
	cmd := exec.Command(c.PDFEngine,
		"--enable-local-file-access",
		"--page-size", "A4",
		"--margin-top", "15mm",
		"--margin-bottom", "15mm",
		"--margin-left", "15mm",
		"--margin-right", "15mm",
		"--print-media-type",
		"--footer-center", "[page]/[topage]",
		"--footer-font-size", "8",
		htmlPath,
		pdfPath,
	)
	output, err := cmd.CombinedOutput()
	if err != nil {
		return fmt.Errorf("wkhtmltopdf failed: %w\nOutput: %s", err, string(output))
	}
	return nil
}

var (
	boldRegex   = regexp.MustCompile(`\*\*(.+?)\*\*`)
	italicRegex = regexp.MustCompile(`\*(.+?)\*`)
	imageRegex  = regexp.MustCompile(`!\[([^\]]*)\]\(([^)]+)\)`)
)

func markdownToHTMLWithID(md string, baseDir string, sectionID string, headingCounter *int) string {
	lines := strings.Split(md, "\n")
	var out []string
	inList := false
	var paragraphLines []string

	// Table state
	inTable := false
	var tableRows []string
	var pendingTableRow string // buffered row waiting for separator confirmation

	flushParagraph := func() {
		if len(paragraphLines) == 0 {
			return
		}
		text := strings.Join(paragraphLines, " ")
		paragraphLines = nil
		if text == "" {
			return
		}
		escaped := html.EscapeString(text)
		escaped = boldRegex.ReplaceAllString(escaped, "<strong>$1</strong>")
		escaped = italicRegex.ReplaceAllString(escaped, "<em>$1</em>")
		escaped = processImages(escaped, baseDir)
		out = append(out, fmt.Sprintf("<p>%s</p>", escaped))
	}

	flushTable := func() {
		if len(tableRows) < 2 {
			// Not a valid table, treat rows as paragraphs
			for _, row := range tableRows {
				if strings.TrimSpace(row) != "" {
					escaped := html.EscapeString(strings.TrimSpace(row))
					escaped = boldRegex.ReplaceAllString(escaped, "<strong>$1</strong>")
					escaped = italicRegex.ReplaceAllString(escaped, "<em>$1</em>")
					out = append(out, fmt.Sprintf("<p>%s</p>", escaped))
				}
			}
			tableRows = nil
			return
		}
		headers := parseTableRow(tableRows[0])
		alignments := parseTableAlign(tableRows[1])
		var htmlOut strings.Builder
		htmlOut.WriteString(`<table><thead><tr>`)
		for i, h := range headers {
			align := ""
			if i < len(alignments) {
				align = alignments[i]
			}
			if align != "" {
				htmlOut.WriteString(fmt.Sprintf(`<th style="text-align:%s">%s</th>`, align, h))
			} else {
				htmlOut.WriteString(fmt.Sprintf(`<th>%s</th>`, h))
			}
		}
		htmlOut.WriteString(`</tr></thead><tbody>`)
		for _, row := range tableRows[2:] {
			cells := parseTableRow(row)
			htmlOut.WriteString(`<tr>`)
			for i, cell := range cells {
				align := ""
				if i < len(alignments) {
					align = alignments[i]
				}
				cellEsc := html.EscapeString(cell)
				cellEsc = boldRegex.ReplaceAllString(cellEsc, "<strong>$1</strong>")
				cellEsc = italicRegex.ReplaceAllString(cellEsc, "<em>$1</em>")
				if align != "" {
					htmlOut.WriteString(fmt.Sprintf(`<td style="text-align:%s">%s</td>`, align, cellEsc))
				} else {
					htmlOut.WriteString(fmt.Sprintf(`<td>%s</td>`, cellEsc))
				}
			}
			htmlOut.WriteString(`</tr>`)
		}
		htmlOut.WriteString(`</tbody></table>`)
		out = append(out, htmlOut.String())
		tableRows = nil
	}

	for _, line := range lines {
		trimmed := strings.TrimSpace(line)

		// Skip empty lines inside table
		if inTable && trimmed == "" {
			continue
		}

		// If we have a pending row and current line is a separator, start table
		if pendingTableRow != "" && isTableSeparator(trimmed) {
			inTable = true
			tableRows = append(tableRows, pendingTableRow)
			tableRows = append(tableRows, trimmed)
			pendingTableRow = ""
			continue
		}

		// If we have a pending row but current line is NOT a separator, flush pending as paragraph
		if pendingTableRow != "" && !isTableRow(trimmed) {
			paragraphLines = append(paragraphLines, pendingTableRow)
			pendingTableRow = ""
		}

		// If we're in a table and see another row, add it
		if inTable && isTableRow(trimmed) {
			tableRows = append(tableRows, trimmed)
			continue
		}

		// If we were in a table but now see non-table content, flush table
		if inTable {
			flushTable()
			inTable = false
		}

		// If line looks like a table row, buffer it (might be table start)
		if isTableRow(trimmed) && !inTable {
			pendingTableRow = trimmed
			continue
		}

		// Handle headings
		if strings.HasPrefix(trimmed, "##### ") {
			flushParagraph()
			if inList {
				out = append(out, "</ul>")
				inList = false
			}
			text := strings.TrimPrefix(trimmed, "##### ")
			*headingCounter++
			id := sectionID + "-h" + strconv.Itoa(*headingCounter)
			out = append(out, fmt.Sprintf(`<h5 id="%s">%s</h5>`, id, html.EscapeString(text)))
		} else if strings.HasPrefix(trimmed, "#### ") {
			flushParagraph()
			if inList {
				out = append(out, "</ul>")
				inList = false
			}
			text := strings.TrimPrefix(trimmed, "#### ")
			*headingCounter++
			id := sectionID + "-h" + strconv.Itoa(*headingCounter)
			out = append(out, fmt.Sprintf(`<h4 id="%s">%s</h4>`, id, html.EscapeString(text)))
		} else if strings.HasPrefix(trimmed, "### ") {
			flushParagraph()
			if inList {
				out = append(out, "</ul>")
				inList = false
			}
			text := strings.TrimPrefix(trimmed, "### ")
			*headingCounter++
			id := sectionID + "-h" + strconv.Itoa(*headingCounter)
			out = append(out, fmt.Sprintf(`<h3 id="%s">%s</h3>`, id, html.EscapeString(text)))
		} else if strings.HasPrefix(trimmed, "## ") {
			flushParagraph()
			if inList {
				out = append(out, "</ul>")
				inList = false
			}
			text := strings.TrimPrefix(trimmed, "## ")
			*headingCounter++
			id := sectionID + "-h" + strconv.Itoa(*headingCounter)
			out = append(out, fmt.Sprintf(`<h2 id="%s">%s</h2>`, id, html.EscapeString(text)))
		} else if strings.HasPrefix(trimmed, "# ") {
			flushParagraph()
			if inList {
				out = append(out, "</ul>")
				inList = false
			}
			text := strings.TrimPrefix(trimmed, "# ")
			*headingCounter++
			id := sectionID + "-h" + strconv.Itoa(*headingCounter)
			out = append(out, fmt.Sprintf(`<h1 id="%s">%s</h1>`, id, html.EscapeString(text)))
		} else if strings.HasPrefix(trimmed, "- ") || strings.HasPrefix(trimmed, "* ") {
			flushParagraph()
			if !inList {
				out = append(out, "<ul>")
				inList = true
			}
			text := strings.TrimPrefix(trimmed, "- ")
			if strings.HasPrefix(trimmed, "* ") {
				text = strings.TrimPrefix(trimmed, "* ")
			}
			escaped := html.EscapeString(text)
			escaped = boldRegex.ReplaceAllString(escaped, "<strong>$1</strong>")
			escaped = italicRegex.ReplaceAllString(escaped, "<em>$1</em>")
			escaped = processImages(escaped, baseDir)
			out = append(out, fmt.Sprintf("<li>%s</li>", escaped))
		} else if trimmed == "" {
			flushParagraph()
			if inList {
				out = append(out, "</ul>")
				inList = false
			}
		} else if imageRegex.MatchString(trimmed) {
			flushParagraph()
			if inList {
				out = append(out, "</ul>")
				inList = false
			}
			out = append(out, processImages(trimmed, baseDir))
		} else {
			if inList {
				out = append(out, "</ul>")
				inList = false
			}
			paragraphLines = append(paragraphLines, trimmed)
		}
	}

	flushParagraph()
	flushTable()
	if inList {
		out = append(out, "</ul>")
	}

	return strings.Join(out, "\n")
}

func isTableRow(line string) bool {
	return strings.HasPrefix(line, "|") && strings.HasSuffix(line, "|") && strings.Count(line, "|") >= 3
}

func isTableSeparator(line string) bool {
	if !isTableRow(line) {
		return false
	}
	inner := strings.Trim(line, "|")
	parts := strings.Split(inner, "|")
	for _, p := range parts {
		p = strings.TrimSpace(p)
		if p == "" {
			continue
		}
		if p[0] != '-' && p[0] != ':' {
			return false
		}
	}
	return true
}

func parseTableRow(row string) []string {
	row = strings.TrimSpace(row)
	row = strings.TrimPrefix(row, "|")
	row = strings.TrimSuffix(row, "|")
	parts := strings.Split(row, "|")
	var result []string
	for _, p := range parts {
		result = append(result, strings.TrimSpace(p))
	}
	return result
}

func parseTableAlign(row string) []string {
	cells := parseTableRow(row)
	var alignments []string
	for _, cell := range cells {
		cell = strings.TrimSpace(cell)
		leftDash := strings.HasPrefix(cell, ":")
		rightDash := strings.HasSuffix(cell, ":")
		if leftDash && rightDash {
			alignments = append(alignments, "center")
		} else if rightDash {
			alignments = append(alignments, "right")
		} else {
			alignments = append(alignments, "left")
		}
	}
	return alignments
}

func markdownToHTML(md string, baseDir string) string {
	counter := 0
	return markdownToHTMLWithID(md, baseDir, "content", &counter)
}

func processImages(text string, baseDir string) string {
	return imageRegex.ReplaceAllStringFunc(text, func(match string) string {
		matches := imageRegex.FindStringSubmatch(match)
		if len(matches) < 3 {
			return match
		}
		alt := matches[1]
		imgPath := matches[2]

		if !filepath.IsAbs(imgPath) {
			// Strip ../ and ./ prefixes — assets are always under campaign root
			for strings.HasPrefix(imgPath, "../") {
				imgPath = strings.TrimPrefix(imgPath, "../")
			}
			for strings.HasPrefix(imgPath, "./") {
				imgPath = strings.TrimPrefix(imgPath, "./")
			}
			imgPath = filepath.Join(baseDir, imgPath)
		}

		data, err := os.ReadFile(imgPath)
		if err != nil {
			return fmt.Sprintf(`<span class="image-missing">[Image: %s]</span>`, html.EscapeString(alt))
		}

		ext := strings.ToLower(filepath.Ext(imgPath))
		var mimeType string
		var content string

		switch ext {
		case ".svg":
			mimeType = "image/svg+xml"
			content = string(data)
			if !strings.Contains(content, "<svg") {
				return fmt.Sprintf(`<span class="image-missing">[Invalid SVG: %s]</span>`, html.EscapeString(alt))
			}
			return fmt.Sprintf(`<div class="campaign-image">%s</div>`, content)
		case ".png":
			mimeType = "image/png"
		case ".jpg", ".jpeg":
			mimeType = "image/jpeg"
		case ".gif":
			mimeType = "image/gif"
		case ".webp":
			mimeType = "image/webp"
		default:
			mimeType = "image/png"
		}

		encoded := base64.StdEncoding.EncodeToString(data)
		dataURI := fmt.Sprintf("data:%s;base64,%s", mimeType, encoded)
		return fmt.Sprintf(`<img src="%s" alt="%s" class="campaign-image"/>`, dataURI, html.EscapeString(alt))
	})
}
